"""Commandes slash dans les transcriptions : une skill ou /plan suivi d'une demande est un
message (titre de la liste, bulle du fil) ; une commande locale (/copy, /rename…) n'en est pas un."""
import json
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

REMOTE = Path(__file__).resolve().parent.parent / "src/claude_hub/remote"
SKILL = "11111111-0000-4000-8000-000000000001"
PLAN = "11111111-0000-4000-8000-000000000002"


def line(**r):
    return json.dumps(r, separators=(",", ":")) + "\n"  # comme claude


def user(content, ts, **r):
    return line(type="user", message={"role": "user", "content": content}, cwd="/tmp/x",
                timestamp=f"2026-11-02T{ts}.000Z", **r)


def reply(text, ts):
    return line(type="assistant", message={"content": [{"type": "text", "text": text}],
                                           "stop_reason": "end_turn"},
                timestamp=f"2026-11-02T{ts}.000Z")


CAVEAT = ("<local-command-caveat>Caveat: The messages below were generated by the user while "
          "running local commands.</local-command-caveat>")


class TestCommandesSlash(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.home = tempfile.mkdtemp()
        proj = Path(cls.home, ".claude/projects/-tmp-x")
        proj.mkdir(parents=True)
        # Skill lancée par `claude -p` (claude-hub) : la commande, puis le texte de la skill (isMeta).
        (proj / f"{SKILL}.jsonl").write_text(
            user("<command-message>check_sentries</command-message>\n"
                 "<command-name>/check_sentries</command-name>", "13:52:02")
            + user([{"type": "text", "text": "Base directory for this skill: /tmp/x/.claude/skills/c\n\n# Check"}],
                   "13:52:02", isMeta=True)
            + reply("Fini.", "13:55:00")
            # /copy dans le terminal : avertissement, commande, sortie ; ni message ni activité.
            + user(CAVEAT, "14:00:00", isMeta=True)
            + user("<command-name>/copy</command-name>\n<command-message>copy</command-message>\n"
                   "<command-args>2</command-args>", "14:00:00"))
        # /plan suivi d'une demande : claude passe en mode plan et répond à la demande.
        (proj / f"{PLAN}.jsonl").write_text(
            user("<command-name>/plan</command-name>\n            <command-message>plan</command-message>\n"
                 "            <command-args>analyse   le ticket\nABC</command-args>", "10:00:00")
            + user("<local-command-stdout>Enabled plan mode</local-command-stdout>", "10:00:00")
            + reply("Voici le plan.", "10:01:00"))

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.home)

    def run_helper(self, interp, script, *args):
        r = subprocess.run([interp, "-", *args], input=(REMOTE / script).read_text(),
                           capture_output=True, text=True, check=True, env={"HOME": self.home,
                                                                             "PATH": "/usr/bin:/bin"})
        return json.loads(r.stdout)

    def sessions(self, interp="python3", script="helper.py"):
        return {s["id"]: s for s in self.run_helper(interp, script, "list")["sessions"]}

    def test_titre(self):
        s = self.sessions()
        self.assertEqual(s[SKILL]["first"], "/check_sentries")
        self.assertEqual(s[PLAN]["first"], "/plan analyse le ticket ABC")

    def test_commande_locale_ignoree(self):
        s = self.sessions()[SKILL]
        self.assertEqual(s["msgs"], 2)  # la skill et son texte ; pas /copy
        self.assertAlmostEqual(s["mtime"] % 86400, 13 * 3600 + 55 * 60)  # /copy n'est pas une activité

    def test_fil(self):
        items = self.run_helper("python3", "helper.py", "history", SKILL, "50")["items"]
        self.assertEqual([(i["role"], i["text"]) for i in items],
                         [("user", "/check_sentries"), ("assistant", "Fini.")])
        items = self.run_helper("python3", "helper.py", "history", PLAN, "50")["items"]
        self.assertEqual([(i["role"], i["text"]) for i in items],
                         [("user", "/plan analyse le ticket ABC"), ("assistant", "Voici le plan.")])

    @unittest.skipUnless(shutil.which("node"), "node absent")
    def test_python_et_node_identiques(self):
        self.assertEqual(self.sessions(), self.sessions("node", "helper.js"))
        for sid in (SKILL, PLAN):
            self.assertEqual(self.run_helper("python3", "helper.py", "history", sid, "50"),
                             self.run_helper("node", "helper.js", "history", sid, "50"))


if __name__ == "__main__":
    unittest.main()
